"""
Task 2D: Inventory NOAA Atlas 14 temporal distribution data availability.

This script does NOT generate hyetographs and does NOT assign temporal
distributions to HUC8s. It only documents what official NOAA Atlas 14
temporal distribution data exists for Volume 9 (Southeastern States) and
whether it can be downloaded programmatically.

Findings confirmed by direct inspection on 2026-07-08:
  - Volume 9 (Southeastern States) temporal distributions cover 6-, 12-,
    24-, and 96-hour durations (matches this project's duration set).
  - The temporal distribution AREA boundaries for Volume 9 are published as
    a stable, directly downloadable shapefile:
      https://hdsc.nws.noaa.gov/pfds/shapefiles/Vol9_Temporals_Shapefiles.zip
    This was downloaded and inspected: it contains a single layer
    "Vol_9_Temporal_Regions" with 2 regions (Region 1, Region 2),
    CRS EPSG:4269 (NAD83 geographic).
  - The per-area, per-duration comma-delimited temporal distribution TABLES
    (the actual quartile/percentile rainfall distribution curves) are served
    through a JavaScript-driven selection form on
    https://hdsc.nws.noaa.gov/pfds/pfds_temporal.html (Volume, Area, Duration
    dropdowns). No static, directly downloadable URL pattern for these CSVs
    was found, so obtaining them requires a manual interactive step.

Because a spatial join of HUC8s to temporal distribution areas plus
selection of early/middle/late-peak/balanced curves is a Task 3 activity
(hyetograph construction), this script stops at documenting availability.

Usage:
  python scripts/inventory_atlas14_temporal_distributions.py
"""

import csv
import os

# --- Section: project defaults (documented, not hidden) ---
ATLAS14_VOLUME = "9"
DURATIONS_HOUR = [6, 12, 24, 96]
TEMPORAL_DISTRIBUTION_AREAS = ["Region 1", "Region 2"]  # from Vol_9_Temporal_Regions.shp

TEMPORAL_PAGE_URL = "https://hdsc.nws.noaa.gov/pfds/pfds_temporal.html"
SHAPEFILE_URL = "https://hdsc.nws.noaa.gov/pfds/shapefiles/Vol9_Temporals_Shapefiles.zip"
SHAPEFILE_LOCAL_PATH = "data/raw/atlas14_temporal_distributions/Vol9_Temporals_Shapefiles.zip"

OUTPUT_PATH = "data/metadata/atlas14_temporal_distribution_inventory.csv"
ACCESS_DATE = "2026-07-08"


def main():
    os.makedirs(os.path.dirname(OUTPUT_PATH), exist_ok=True)
    shapefile_downloaded = os.path.exists(SHAPEFILE_LOCAL_PATH)

    rows = []

    # --- Row: the temporal distribution AREA shapefile (directly downloadable) ---
    rows.append({
        "atlas14_volume": ATLAS14_VOLUME,
        "duration_hour": "",  # applies to all durations; areas are duration-independent
        "temporal_distribution_area": "all (Region 1, Region 2)",
        "source_url": SHAPEFILE_URL,
        "file_format": "Shapefile (zipped .shp/.shx/.dbf/.prj/.cpg)",
        "local_path": SHAPEFILE_LOCAL_PATH,
        "status": "downloaded" if shapefile_downloaded else "pending_manual_download",
        "notes": (
            "Confirmed via direct download and inspection: 2 temporal regions "
            "(Region 1, Region 2), CRS EPSG:4269 (NAD83 geographic). This "
            "shapefile could support a spatial join of HUC8s to temporal "
            "regions, but that assignment is deferred to Task 3 per project "
            "scope, not because the data is unavailable."
        ),
        "access_date": ACCESS_DATE,
    })

    # --- Rows: per-duration, per-area comma-delimited temporal distribution tables ---
    for duration_hour in DURATIONS_HOUR:
        for area in TEMPORAL_DISTRIBUTION_AREAS:
            rows.append({
                "atlas14_volume": ATLAS14_VOLUME,
                "duration_hour": duration_hour,
                "temporal_distribution_area": area,
                "source_url": TEMPORAL_PAGE_URL,
                "file_format": "Comma-delimited text (.csv), served via interactive form",
                "local_path": "data/raw/atlas14_temporal_distributions/ (not yet populated)",
                "status": "pending_manual_download",
                "notes": (
                    "NOAA states these are downloadable as comma-delimited files per "
                    "temporal distribution area and duration, but the download is "
                    "generated by a JavaScript Volume/Area/Duration selection form; "
                    "no static per-file URL pattern was found. Manual step: open "
                    f"{TEMPORAL_PAGE_URL}, select Volume 9, {area}, "
                    f"{duration_hour}-hour duration, and save the resulting table."
                ),
                "access_date": ACCESS_DATE,
            })

    fieldnames = [
        "atlas14_volume", "duration_hour", "temporal_distribution_area", "source_url",
        "file_format", "local_path", "status", "notes", "access_date",
    ]
    with open(OUTPUT_PATH, "w", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(rows)

    print(f"Wrote {len(rows)} rows to {OUTPUT_PATH}")


if __name__ == "__main__":
    main()
